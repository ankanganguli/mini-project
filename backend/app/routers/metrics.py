import json
import os
import logging
from fastapi import APIRouter
from backend.app.schemas.response import MetricsResponse
from backend.app.database import db_client
from backend.app.config import settings

logger = logging.getLogger(__name__)

router = APIRouter()

@router.get("/metrics", response_model=MetricsResponse)
async def get_system_metrics():
    """
    Returns aggregate system metrics including model performance evaluation metrics
    and total verification counts from the audit trail.
    """
    # 1. Fetch total verifications from DB
    try:
        total_verifications = await db_client.verifications.count_documents({})
    except Exception as e:
        logger.error(f"Error fetching verification count: {e}")
        total_verifications = 0
        
    # 2. Load latest model metrics from disk (generated by train_engine.py)
    model_accuracy = 0.0
    precision = 0.0
    recall = 0.0
    f1_score = 0.0
    dataset_samples = 0
    
    if os.path.exists(settings.METRICS_PATH):
        try:
            with open(settings.METRICS_PATH, 'r') as f:
                metrics = json.load(f)
                
                model_accuracy = metrics.get("accuracy", 0.0)
                precision = metrics.get("precision", 0.0)
                recall = metrics.get("recall", 0.0)
                f1_score = metrics.get("f1_score", 0.0)
                dataset_samples = metrics.get("training_samples", 0)
        except Exception as e:
            logger.error(f"Error reading metrics file {settings.METRICS_PATH}: {e}")
            
    return MetricsResponse(
        model_accuracy=model_accuracy,
        precision=precision,
        recall=recall,
        f1_score=f1_score,
        total_verifications=total_verifications,
        dataset_samples=dataset_samples
    )
